export function localizeDefaultRule(rule: InputRule, locale: Locale): InputRule {
  const cloned = JSON.parse(JSON.stringify(rule)) as InputRule;
  if (locale === "zh") return cloned;
  return {
    ...cloned,
    group: GROUP_EN_MAP[cloned.group] ?? cloned.group,
    name: RULE_NAME_EN_MAP[cloned.id] ?? cloned.name,
  };
}
