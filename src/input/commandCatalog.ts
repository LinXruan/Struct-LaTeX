function buildCatalog(): { commands: Set<string>; prefixes: Set<string> } {
  const commands = new Set<string>(EXTRA_MATH_COMMANDS);

  for (const cmd of COMMAND_SIGNATURES.keys()) commands.add(cmd);
  for (const cmd of COMMAND_DELIMS) commands.add(cmd);
  for (const cmd of POSTFIX_MODIFIER_COMMANDS) commands.add(cmd);

  const prefixes = new Set<string>();
  for (const cmd of commands) {
    if (!cmd.startsWith("\\") || cmd.length < 2) continue;
    if (!/^\\[a-zA-Z]+$/.test(cmd)) continue;
    for (let len = 2; len <= cmd.length; len++) {
      prefixes.add(cmd.slice(0, len));
    }
  }

  return { commands, prefixes };
}

const CATALOG = buildCatalog();

export const KNOWN_COMMANDS: ReadonlySet<string> = CATALOG.commands;
export const KNOWN_COMMAND_PREFIXES: ReadonlySet<string> = CATALOG.prefixes;

export function isKnownCommand(cmd: string): boolean {
  return KNOWN_COMMANDS.has(cmd);
}

export function isCommandPrefix(prefix: string): boolean {
  return KNOWN_COMMAND_PREFIXES.has(prefix);
}
